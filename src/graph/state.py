"""Typed state definition for the multi-agent developer team."""

from typing import Dict, List, Any, Optional
from pydantic import BaseModel, Field
from ..tools.firewall_filter import ToolAuditEntry


class TeamState(BaseModel):
    """Global state passed across the cyclic multi-agent graph."""
    task: str = Field(description="The primary objective requested by the user")
    spec: str = Field(default="", description="Architectural specification generated by Architect")
    plan: List[str] = Field(default_factory=list, description="Step-by-step execution roadmap")
    files_modified: List[str] = Field(default_factory=list, description="List of files created or modified")
    
    # Testing & Verification Loop
    test_command: str = Field(default="pytest", description="Test suite command to execute")
    test_output: str = Field(default="", description="Captured stdout/stderr from test runner")
    tests_passed: bool = Field(default=False, description="Whether all tests passed 100%")
    iteration_count: int = Field(default=0, description="Number of developer-tester feedback iterations")
    max_iterations: int = Field(default=5, description="Maximum allowed feedback cycles before escalation")
    
    # Review & Audit
    review_approved: bool = Field(default=False, description="Whether Security & Reviewer approved changes")
    review_comments: List[str] = Field(default_factory=list, description="Feedback from reviewer")
    
    # Security & Ledger
    audit_trail: List[ToolAuditEntry] = Field(default_factory=list, description="ToolGate security decisions")
    status: str = Field(default="INITIALIZED", description="Current operational state")
